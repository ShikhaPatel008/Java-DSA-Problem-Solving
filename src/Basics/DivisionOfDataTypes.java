package Basics;

public class DivisionOfDataTypes {
     static void main(String[] args){
        double x = 5 / 2;
        System.out.println(x);
        double y = 5.0 / 2;
        System.out.println(y);
        double a = 5 / 2.0;
        System.out.println(a);
        double b = 5.0 / 2.0;
        System.out.println(b);
    }

}
