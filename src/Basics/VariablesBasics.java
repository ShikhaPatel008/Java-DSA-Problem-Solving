package Basics;

public class VariablesBasics {
    static void main(String[] args) {
        int x = 10;
        int y = 6;
        System.out.print(x + " "); // here + appends the space after value of x
        System.out.print(x-5 + " right"); // here + appends space along with right after the given value i.e. anything written in double quotes after + sign is appended next to the given argument
        System.out.println(x + y);
        x = 20; // value of x is updated from 10 to 20
        System.out.println(x);
        x = x - 4;
        System.out.println(x);
        y = y - 10;
        System.out.println(y);
        y = y / 2;
        System.out.println(y);



    }

    }

